function t(key, vars = {}) {
  const value = I18N[key]?.[LANG === "en" ? 1 : 0];
  if (typeof value === "function") return value(vars);
  return (value ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

function applyStaticTranslations() {
  if (LANG === "de") return;
  for (const node of document.querySelectorAll("[data-i18n]")) node.innerHTML = t(node.dataset.i18n);
  for (const [attr, name] of [["i18nPlaceholder", "placeholder"], ["i18nTitle", "title"], ["i18nAria", "aria-label"]]) {
    for (const node of document.querySelectorAll(`[data-${attr.replace(/[A-Z]/g, c => "-" + c.toLowerCase())}]`)) node.setAttribute(name, t(node.dataset[attr]));
  }
}

